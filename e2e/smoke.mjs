import { chromium } from '@playwright/test'
import { existsSync, mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

const baseURL = process.env.E2E_URL || 'http://127.0.0.1:5173'
const username = process.env.E2E_USERNAME || 'admin'
const password = process.env.E2E_PASSWORD || 'very-long-admin-password'
const screenshots = resolve('artifacts')
mkdirSync(screenshots, { recursive: true })
const macChrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
const browser = await chromium.launch({ headless: true, ...(existsSync(macChrome) ? { executablePath: macChrome } : {}) })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
  await page.goto(baseURL)
  await page.waitForLoadState('networkidle')
  if (await page.getByText('Crea il tuo spazio').isVisible().catch(() => false)) {
    await page.getByPlaceholder('Dal tuo stack Docker').fill(process.env.E2E_SETUP_KEY || '')
    await page.getByPlaceholder('Come vuoi apparire').fill('Admin')
    await page.getByPlaceholder('es. enrico').fill(username)
    await page.getByPlaceholder('••••••••••••').fill(password)
    await page.getByRole('button', { name: /Crea amministratore/ }).click()
  } else if (await page.getByText('Accedi al tuo spazio').isVisible().catch(() => false)) {
    await page.getByPlaceholder('es. enrico').fill(username)
    await page.getByPlaceholder('••••••••••••').fill(password)
    await page.getByRole('button', { name: /Accedi/ }).click()
  }
  await page.getByText('Insieme si conta meglio').waitFor({ timeout: 10000 })
  await page.screenshot({ path: `${screenshots}/dashboard-desktop.png`, fullPage: true })
  await page.getByRole('combobox', { name: 'Tema' }).first().selectOption('amoled')
  await page.reload()
  if (await page.locator('html').getAttribute('data-theme') !== 'amoled') throw new Error('Il tema AMOLED non persiste al riavvio')
  await page.waitForTimeout(150)
  await page.screenshot({ path: `${screenshots}/dashboard-amoled-desktop.png`, fullPage: true })
  await page.getByRole('combobox', { name: 'Tema' }).first().selectOption('light')
  if (await page.getByText('Il tuo primo gruppo ti aspetta').isVisible().catch(() => false)) {
    await page.getByRole('button', { name: /Crea il primo gruppo/ }).click()
    await page.getByPlaceholder('es. Weekend a Lisbona').fill('Weekend a Lisbona')
    await page.getByPlaceholder('Anna, Marco, Luca').fill('Anna, Marco, Luca')
    await page.getByRole('dialog', { name: 'Crea un gruppo' }).getByRole('button', { name: 'Crea gruppo', exact: true }).click()
  } else {
    await page.locator('.group-card').first().click()
  }
  await page.getByText('Le spese del gruppo').waitFor({ timeout: 10000 })
  await page.screenshot({ path: `${screenshots}/group-desktop.png`, fullPage: true })
  await page.getByRole('combobox', { name: 'Tema' }).first().selectOption('amoled')
  await page.waitForTimeout(150)
  await page.screenshot({ path: `${screenshots}/group-amoled-desktop.png`, fullPage: true })
  await page.getByRole('combobox', { name: 'Tema' }).first().selectOption('light')
  await page.getByRole('button', { name: 'Aggiungi spesa' }).first().click()
  const expenseDialog = page.getByRole('dialog', { name: 'Nuova spesa' })
  await expenseDialog.getByLabel('Titolo').fill('Cena di prova')
  await expenseDialog.getByRole('textbox', { name: 'Importo (EUR)' }).fill('42,50')
  await expenseDialog.screenshot({ path: `${screenshots}/expense-desktop.png` })
  await expenseDialog.getByRole('button', { name: 'Aggiungi spesa' }).click()
  await page.getByText('Cena di prova').first().waitFor()
  await page.getByRole('tab', { name: 'Permessi' }).click()
  await page.getByText('Permessi del gruppo').waitFor()
  await page.screenshot({ path: `${screenshots}/permissions-desktop.png`, fullPage: true })
  await page.getByRole('button', { name: 'Invita persona' }).click()
  await page.getByRole('button', { name: 'Genera link di invito' }).click()
  await page.getByLabel('Link di invito').waitFor()
  await page.getByRole('dialog', { name: 'Invita una persona' }).screenshot({ path: `${screenshots}/invite-desktop.png` })
  const inviteUrl = await page.getByLabel('Link di invito').inputValue()
  const guest = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
  await guest.goto(inviteUrl)
  await guest.getByText(/Entra in Weekend a Lisbona/).waitFor()
  await guest.getByPlaceholder('Come vuoi apparire').fill('Ospite QA')
  const guestUsername = `ospite${Date.now()}`
  await guest.getByPlaceholder('es. enrico').fill(guestUsername)
  await guest.getByPlaceholder('••••••••••••').fill('very-long-guest-password')
  await guest.getByRole('button', { name: /Crea account ed entra/ }).click()
  await guest.getByText('Le spese del gruppo').waitFor({ timeout: 10000 })
  const guestGroupId = new URL(guest.url()).hash.match(/group\/([^/]+)/)?.[1]
  if (!guestGroupId) throw new Error('Il link di invito non ha aperto il gruppo')
  const guestCreateStatus = await guest.evaluate(async () => (await fetch('/api/groups', {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ name: 'Privato', currency: 'EUR', participants: [{ name: 'Io' }] }),
  })).status)
  if (guestCreateStatus !== 403) throw new Error(`L'invitato ha creato un gruppo: ${guestCreateStatus}`)
  await guest.screenshot({ path: `${screenshots}/guest-mobile.png`, fullPage: true })
  await guest.getByRole('button', { name: 'Apri il tuo account' }).click()
  await guest.getByRole('heading', { name: 'Impostazioni personali' }).waitFor()
  await guest.screenshot({ path: `${screenshots}/profile-mobile.png`, fullPage: true })
  await guest.getByLabel('Password attuale').fill('very-long-guest-password')
  await guest.getByLabel('Nuova password', { exact: true }).fill('another-long-guest-password')
  await guest.getByLabel('Conferma nuova password').fill('another-long-guest-password')
  await guest.getByRole('button', { name: 'Aggiorna password' }).click()
  await guest.getByText('Password aggiornata. Le altre sessioni sono state disconnesse.').waitFor()
  await guest.goto(`${baseURL}/#/group/${guestGroupId}`)
  await guest.getByText('Le spese del gruppo').waitFor()
  await page.getByRole('dialog', { name: 'Invita una persona' }).getByRole('button', { name: 'Chiudi' }).click()
  await page.getByRole('tab', { name: 'Persone' }).click()
  await page.getByLabel('Account di Marco').selectOption({ label: `Ospite QA (@${guestUsername})` })
  await page.getByText('Collegato a un account').waitFor()
  await page.getByRole('tab', { name: 'Spese' }).click()
  await page.getByRole('tab', { name: 'Permessi' }).click()
  const member = page.locator('.member-row').filter({ hasText: guestUsername })
  await member.getByRole('button', { name: 'Modifica permessi' }).click()
  const permissionDialog = page.getByRole('dialog', { name: 'Permessi di Ospite QA' })
  await permissionDialog.screenshot({ path: `${screenshots}/permission-editor-desktop.png` })
  await permissionDialog.getByRole('button', { name: 'lettore' }).click()
  await permissionDialog.getByRole('button', { name: 'Salva permessi' }).click()
  const guestAddStatus = await guest.evaluate(async (groupId) => (await fetch(`/api/groups/${groupId}/expenses`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, guestGroupId)
  if (guestAddStatus !== 403) throw new Error(`L'invitato ha ancora accesso in scrittura: ${guestAddStatus}`)
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
  await mobile.goto(baseURL)
  await mobile.waitForLoadState('networkidle')
  if (await mobile.getByText('Accedi al tuo spazio').isVisible().catch(() => false)) {
    await mobile.getByPlaceholder('es. enrico').fill(username)
    await mobile.getByPlaceholder('••••••••••••').fill(password)
    await mobile.getByRole('button', { name: /Accedi/ }).click()
  }
  await mobile.getByText('Insieme si conta meglio').waitFor({ timeout: 10000 })
  await mobile.screenshot({ path: `${screenshots}/dashboard-mobile.png`, fullPage: true })
  await mobile.getByRole('combobox', { name: 'Tema' }).first().selectOption('amoled')
  await mobile.waitForTimeout(150)
  await mobile.screenshot({ path: `${screenshots}/dashboard-amoled-mobile.png`, fullPage: true })
  await mobile.getByRole('combobox', { name: 'Tema' }).first().selectOption('light')
  await mobile.locator('.group-card').first().click()
  await mobile.getByText('Le spese del gruppo').waitFor({ timeout: 10000 })
  await mobile.screenshot({ path: `${screenshots}/group-mobile.png`, fullPage: true })
  await mobile.getByRole('combobox', { name: 'Tema' }).first().selectOption('amoled')
  await mobile.waitForTimeout(150)
  await mobile.screenshot({ path: `${screenshots}/group-amoled-mobile.png`, fullPage: true })
  await mobile.getByRole('combobox', { name: 'Tema' }).first().selectOption('light')
  await mobile.getByRole('button', { name: 'Aggiungi spesa' }).first().click()
  await mobile.getByRole('dialog', { name: 'Nuova spesa' }).screenshot({ path: `${screenshots}/expense-mobile.png` })
  console.log('Browser smoke passed; screenshots in', screenshots)
} finally { await browser.close() }
